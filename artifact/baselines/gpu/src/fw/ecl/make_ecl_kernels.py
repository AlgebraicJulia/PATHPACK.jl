#!/usr/bin/env python3
"""Extract the ECL-APSP v1.0 kernels (ECL-APSP_10.cu, sha1 2263a1c3...) into ecl_kernels.cuh with
the minimal portability patches the survey lists:
  * 64-bit element indices (the original int indices overflow once upper^2 > 2^31, i.e. n > 46340)
  * init1 as a 64-bit grid-stride loop (the original launches upper^2/1024 blocks with int math)
No algorithmic change: same tiles (64x64, 1024 threads, 2x2 per thread), same kernels, same order.
usage: make_ecl_kernels.py ECL-APSP_10.cu > ecl_kernels.cuh"""
import re, sys
src = open(sys.argv[1]).read()
a = src.index("using mtype = int;")
b = src.index("static void CheckCuda()")
k = src[a:b]
# 64-bit index variables
k = re.sub(r"const int (idx0_\w+) =", r"const size_t \1 =", k)
k = k.replace("int idx2_a = (x * tile) * upper + j_a;", "size_t idx2_a = (size_t)(x * tile) * upper + j_a;")
k = k.replace("int idx2_b = (x * tile) * upper + j_b;", "size_t idx2_b = (size_t)(x * tile) * upper + j_b;")
k = re.sub(r"const size_t (idx0_\w+) = (\w+) \* upper \+ (\w+);", r"const size_t \1 = (size_t)\2 * upper + \3;", k)
k = re.sub(r"kcols\[(i_[ab]) \* upper \+", r"kcols[(size_t)\1 * upper +", k)
k = re.sub(r"krows\[\(x \* tile \+ (warp_[ab])\) \* upper \+", r"krows[(size_t)(x * tile + \1) * upper +", k)
k = k.replace("AdjMat[i * upper + nei] = g.eweight[j];", "AdjMat[(size_t)i * upper + nei] = g.eweight[j];")
# init1: grid-stride, 64-bit
old_init1 = k[k.index("static __global__ void init1"):k.index("// add edges to adj matrix")]
new_init1 = '''static __global__ void init1(const int nodes, mtype* const __restrict__ AdjMat, const int upper)
{
  const size_t total = (size_t)upper * upper;
  for (size_t idx = threadIdx.x + (size_t)blockIdx.x * blockDim.x; idx < total; idx += (size_t)gridDim.x * blockDim.x) {
    const size_t i = idx / upper;
    const size_t j = idx % upper;
    AdjMat[idx] = ((i == j) && (i < (size_t)nodes)) ? 0 : (INT_MAX / 2);
  }
}

'''
k = k.replace(old_init1, new_init1)
hdr = "// Generated by make_ecl_kernels.py from ECL-APSP v1.0 (Liu & Burtscher, Texas State University,\n// BSD-3-Clause, https://cs.txstate.edu/~burtscher/research/ECL-APSP/). Kernels unchanged except\n// 64-bit indexing; see make_ecl_kernels.py.\n#pragma once\n#include <climits>\n"
sys.stdout.write(hdr + k)
